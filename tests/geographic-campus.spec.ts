import { test, expect } from '@playwright/test'
import { shot } from './shot'

test('the 3D campus can be rotated, panned and zoomed, and context is not audit evidence', async ({ page }) => {
  await page.goto('/')
  const scene = page.getByTestId('campus-scene3d')
  await expect(scene).toHaveAttribute('data-building-count', '232')
  await expect(scene.locator('canvas')).toBeVisible()
  await expect(scene).toHaveAttribute('data-azimuth', /\d/)
  const azimuth = async () => Number(await scene.getAttribute('data-azimuth'))
  const zoom = async () => Number(await scene.getAttribute('data-zoom'))
  await expect.poll(azimuth).toBeCloseTo(28, 0)
  const initial = await azimuth()
  await page.getByRole('button', { name: 'Rotate view right', exact: true }).click()
  await expect.poll(azimuth).toBeGreaterThan(initial + 40)
  await page.getByRole('button', { name: 'Rotate view left', exact: true }).click()
  await expect.poll(azimuth).toBeLessThan(initial + 5)
  // Pointer drag orbits the camera.
  const rect = (await scene.boundingBox())!
  await page.mouse.move(rect.x + rect.width * .5, rect.y + rect.height * .5)
  await page.mouse.down()
  await page.mouse.move(rect.x + rect.width * .5 + 160, rect.y + rect.height * .5, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => Math.abs((await azimuth()) - initial)).toBeGreaterThan(10)
  await page.getByRole('button', { name: 'Reset campus', exact: true }).click()
  await expect.poll(async () => Math.abs((await azimuth()) - 28)).toBeLessThan(1)
  // Keyboard rotation and zoom.
  await scene.focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(azimuth, { timeout: 20000 }).toBeGreaterThan(40)
  await page.keyboard.press('+')
  await expect.poll(zoom, { timeout: 20000 }).toBeGreaterThan(1.3)
  await page.getByRole('button', { name: 'Reset campus', exact: true }).click()
  await page.getByRole('button', { name: 'Show building list', exact: true }).click()
  const list = page.locator('.index-popover')
  await expect(list.locator('.index-row')).toHaveCount(232)
  await list.getByRole('combobox', { name: 'Building type', exact: true }).selectOption('Audit scope')
  await expect(list.locator('.index-row')).toHaveCount(12)
  await list.getByRole('combobox', { name: 'Building type', exact: true }).selectOption('All buildings')
  await list.getByRole('textbox', { name: 'Search buildings', exact: true }).fill('Thomason')
  await list.locator('.index-row').focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.evidence-content h2')).toHaveText('James Thomason Building')
  await expect(page.locator('.context-evidence')).toContainText('Not audited')
  await expect(page.locator('.context-evidence')).toContainText('photo-based estimate')
  await expect(page.locator('.context-evidence .case-card')).toHaveCount(0)
  await expect(scene).toHaveAttribute('data-selected', 'osm-relation-8255183')
  await page.getByRole('button', { name: 'Focus selected building', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Focus selected building', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(zoom, { timeout: 10000 }).toBeGreaterThan(3.5)
  await page.waitForTimeout(500)
  await shot(page, 'artifacts/designs/geographic-main-focused.png')
  await page.getByRole('button', { name: 'Reset campus', exact: true }).click()
  await expect.poll(zoom, { timeout: 10000 }).toBeLessThan(1.1)
})

test('current campus source data is publicly reproducible', async ({ request }) => {
  const response = await request.get('/campus/manifest.json')
  expect(response.ok()).toBe(true)
  const manifest = await response.json()
  expect(manifest.statistics).toMatchObject({ buildings: 231, auditBuildings: 12, roads: 229, surfaces: 47, trees: 17 })
  expect(manifest.license).toBe('ODbL-1.0')
  expect(manifest.diagnostics).toEqual([])
  const chunks = await Promise.all(Array.from({ length: 5 }, (_, i) => request.get('/campus/buildings-' + i + '.json').then(r => r.json())))
  expect(chunks.flat()).toHaveLength(231)
  expect(chunks.flat().find(b => b.id === 'govind').rings.some((r: { role: string }) => r.role === 'inner')).toBe(true)
})
