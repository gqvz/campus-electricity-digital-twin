import { z } from 'zod'
import { verifiedHoursBetween } from './calc'

export const deviceOptions = [
  { value: 'lights', label: 'Lights', defaultWatts: 20 },
  { value: 'fans', label: 'Fans', defaultWatts: 65 },
  { value: 'ac', label: 'Air conditioner', defaultWatts: 1200 },
  { value: 'other', label: 'Other', defaultWatts: 100 },
] as const

const localDateTime = z.string().min(1, 'Choose the date and time you saw it')

export const observationSchema = z.object({
  buildingId: z.string().min(1, 'Choose a building'),
  floor: z.coerce.number().int('Whole floors only').min(0, 'Ground floor is 0').max(40),
  zoneName: z.string().trim().min(1, 'Name the room or zone').max(120),
  device: z.enum(['lights', 'fans', 'ac', 'other']),
  deviceCount: z.coerce.number().int('Whole devices only').min(1, 'At least one device').max(500),
  unitWatts: z.coerce.number().int('Whole watts only').min(1, 'Enter watts per device').max(5000),
  occupied: z.boolean(),
  observedAt: localDateTime,
  verifiedAt: z.string().optional(),
  confidence: z.enum(['direct', 'inferred']),
  recommendation: z.string().trim().max(400).optional(),
  privateNotes: z.string().trim().max(1000).optional(),
}).superRefine((v, ctx) => {
  if (v.verifiedAt) {
    if (verifiedHoursBetween(new Date(v.observedAt), new Date(v.verifiedAt)) === null) {
      ctx.addIssue({ code: 'custom', path: ['verifiedAt'], message: 'Must be later than the sighting, and within 24 hours' })
    }
  }
})
export type ObservationInput = z.infer<typeof observationSchema>

/** Row for `observations`. watts/kwh are generated by the database. */
export function toRow(input: ObservationInput, sessionId: string) {
  const observed = new Date(input.observedAt)
  const verified = input.verifiedAt ? new Date(input.verifiedAt) : null
  const hours = verified ? verifiedHoursBetween(observed, verified) : null
  return {
    session_id: sessionId, building_id: input.buildingId, floor: input.floor, zone_name: input.zoneName,
    device: input.device, device_count: input.deviceCount, unit_watts: input.unitWatts, occupied: input.occupied,
    observed_at: observed.toISOString(), verified_at: hours ? verified!.toISOString() : null, verified_hours: hours,
    confidence: input.confidence, recommendation: input.recommendation || null, private_notes: input.privateNotes || null,
  }
}
