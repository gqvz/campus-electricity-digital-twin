import { describe, expect, it } from 'vitest'
import { observationSchema, toRow } from './observation'

const base = {
  buildingId: 'lhc', floor: 1, zoneName: 'Classroom B-201', device: 'fans' as const, deviceCount: 8, unitWatts: 65,
  occupied: false, observedAt: '2026-10-14T20:35', confidence: 'direct' as const,
}

describe('observation form schema', () => {
  it('accepts a point sighting and produces no duration', () => {
    const parsed = observationSchema.parse(base)
    const row = toRow(parsed, 's1')
    expect(row.verified_hours).toBeNull()
    expect(row.verified_at).toBeNull()
    expect(row).not.toHaveProperty('watts')   // generated by the database
  })
  it('derives hours from a later shutdown time', () => {
    const row = toRow(observationSchema.parse({ ...base, verifiedAt: '2026-10-14T22:05' }), 's1')
    expect(row.verified_hours).toBe(1.5)
  })
  it('rejects a shutdown time before the sighting', () => {
    expect(observationSchema.safeParse({ ...base, verifiedAt: '2026-10-14T20:00' }).success).toBe(false)
  })
  it('rejects empty and out-of-range fields', () => {
    expect(observationSchema.safeParse({ ...base, zoneName: ' ' }).success).toBe(false)
    expect(observationSchema.safeParse({ ...base, deviceCount: 0 }).success).toBe(false)
    expect(observationSchema.safeParse({ ...base, unitWatts: 99999 }).success).toBe(false)
  })
})
