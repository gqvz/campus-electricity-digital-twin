// Generates supabase/seed.sql from the same building list the app renders.
//   npx vite-node tools/gen-seed.ts
import { writeFileSync } from 'node:fs'
import { campusBuildings } from '../src/designs/fixtures'

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const rows = campusBuildings.map(b => `  (${q(b.id)}, ${q(b.name)}, ${q(b.kind)}, ${b.floors}, ${b.auditScope ? 'true' : 'false'})`)
writeFileSync('supabase/seed.sql', `-- Generated by tools/gen-seed.ts. Do not edit by hand.
insert into public.buildings (id, name, kind, floors, audit_scope) values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, kind = excluded.kind, floors = excluded.floors, audit_scope = excluded.audit_scope;
`)
console.log(`seeded ${rows.length} buildings`)
